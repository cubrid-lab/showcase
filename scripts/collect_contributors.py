#!/usr/bin/env python3
"""Collect the outside contributors of the four CUBRID Python repositories.

Writes events/2026-ossdevcon/metrics/contributors-YYYY-MM-DD.json in the same
shape as contributors-2026-10-28.json. Earlier snapshots are never rewritten.

External contributor: a GitHub account of type User, not a maintainer and not a
bot or automation account, that authored at least one pull request with
merged_at set in one of the four repositories.

Requires the gh CLI, authenticated.

Usage:
    python3 scripts/collect_contributors.py [--date YYYY-MM-DD]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "events/2026-ossdevcon/metrics"
REPOS = ("pycubrid", "sqlalchemy-cubrid", "cubrid-cookbook-python", "cubrid-mcp-server")
ORG = "cubrid-lab"


def gh(path: str) -> list | dict:
    out = subprocess.run(["gh", "api", "--paginate", "--slurp", path],
                         check=True, capture_output=True, text=True).stdout
    pages = json.loads(out)
    if pages and isinstance(pages[0], list):
        return [item for page in pages for item in page]
    return pages[0] if len(pages) == 1 else pages


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", default=dt.date.today().isoformat())
    args = parser.parse_args()

    previous = json.loads((METRICS / "contributors-2026-10-28.json").read_text(encoding="utf-8"))
    maintainers = previous["maintainers"]
    excluded = previous["excludedAccounts"]
    skip = {m["login"] for m in maintainers} | set(excluded["bots"])
    skip |= {entry.split(" ")[0] for entry in excluded["automation"]}
    known = {c["login"]: c for c in previous["externalContributors"]}

    contributors: dict[str, dict] = {}
    others: dict[str, dict] = {}
    good_first: list[dict] = []
    for repo in REPOS:
        for pr in gh(f"repos/{ORG}/{repo}/pulls?state=all&per_page=100"):
            user = pr["user"]
            login = user["login"]
            if user["type"] != "User" or login in skip:
                continue
            if pr["merged_at"]:
                entry = contributors.setdefault(login, {"login": login, "repos": {}})
                entry["repos"].setdefault(repo, []).append({
                    "type": "merged_pr", "number": pr["number"], "title": pr["title"],
                    "url": pr["html_url"], "mergedAt": pr["merged_at"]})
            else:
                kind = "pr_open" if pr["state"] == "open" else "pr_not_merged"
                entry = others.setdefault(login, {"login": login, "repos": {}})
                entry["repos"].setdefault(repo, []).append({
                    "type": kind, "number": pr["number"], "title": pr["title"], "url": pr["html_url"]})
        for issue in gh(f"repos/{ORG}/{repo}/issues?state=open&labels=good%20first%20issue&per_page=100"):
            if "pull_request" not in issue:
                good_first.append({"repo": repo, "number": issue["number"], "title": issue["title"],
                                   "url": issue["html_url"],
                                   "labels": [label["name"] for label in issue["labels"]]})

    for login, entry in contributors.items():
        old = known.get(login)
        if old:
            entry.update({k: old[k] for k in ("name", "avatarUrl", "profile", "accountCreated") if k in old})
        else:
            user = gh(f"users/{login}")
            entry.update({"name": user.get("name"), "avatarUrl": user["avatar_url"],
                          "profile": user["html_url"], "accountCreated": user["created_at"]})
        entry["repos"] = dict(sorted(entry["repos"].items()))
    for login in list(others):
        if login in contributors:
            del others[login]

    ordered = sorted(contributors.values(),
                     key=lambda c: (-sum(len(v) for v in c["repos"].values()), c["login"].lower()))
    snapshot = {
        "snapshotUtc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "repos": [f"{ORG}/{r}" for r in REPOS],
        "maintainers": maintainers,
        "externalContributorCount": len(ordered),
        "externalMergedPrCount": sum(len(v) for c in ordered for v in c["repos"].values()),
        "externalContributors": ordered,
        "otherParticipants": sorted(others.values(), key=lambda c: c["login"].lower()),
        "goodFirstIssues": good_first,
        "excludedAccounts": excluded,
        "method": previous["method"].split(" Issues, unmerged PRs")[0]
        + " Authors of unmerged or open PRs are listed under otherParticipants; issue authors and"
        " reviewers are not collected by this script. Generated by scripts/collect_contributors.py.",
    }
    out = METRICS / f"contributors-{args.date}.json"
    out.write_text(json.dumps(snapshot, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {snapshot['externalContributorCount']} contributors, "
          f"{snapshot['externalMergedPrCount']} merged PRs, {len(good_first)} good first issues")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
